#' Estimate Phenological Centroid (Day of Biological Year)
#'
#' Calculates the circular, abundance-weighted centroid across simulated posterior
#' probability density curves using the Day of Biological Year (DOBY) axis rotation.
#' Posterior summaries (`Mean`, `Lower_CI`, `Upper_CI`) are computed on the
#' continuous unwrapped `DOBY` timeline prior to modulo back-transformation onto
#' calendar `DOY`, preventing artificial boundary averaging when phenological
#' centroids straddle December 31 and January 1.
#'
#' @param sim_mat A numeric matrix (`n_grid x n_sims`, typically `365 x 1000`) of normalized posterior probability density curves generated by [simulate_posterior_density()].
#' @param ref_sim_mat Optional reference posterior density matrix (`n_grid x n_sims`) used to anchor the biological minimum day (`D_min`) consistently across environmental gradients or scenario comparisons (important for bimodal aestivating taxa where winter and summer troughs have similar depth). Defaults to `NULL` (computes `D_min` from `sim_mat` itself).
#' @return A list containing the posterior `Mean`, `Lower_CI` (2.5%), `Upper_CI` (97.5%) on the calendar `DOY` scale, `Posterior_Draws` (calendar `DOY`), `DOBY_Draws` (unwrapped biological-year coordinates), and the biological minimum day `D_min`.
#' @examples
#' data(sim_carabids)
#' mod <- mgcv::gam(
#'   Count ~ s(DOY, bs = "cc", k = 10) + s(Latitude, k = 4) + offset(LogEffort),
#'   family = poisson(), data = sim_carabids,
#'   knots = list(DOY = c(0.5, 365.5))
#' )
#' nd <- create_newdata(mod, doy = "DOY", Latitude = "mean")
#' sim <- simulate_posterior_density(mod, nd, n_sims = 100, warnings = FALSE)
#' estimate_centroid(sim)$Mean
#' @export
estimate_centroid <- function(sim_mat, ref_sim_mat = NULL) {
  grid <- get_doy_grid(sim_mat)
  n_rows <- grid$n_rows
  dt <- grid$dt

  if (!is.null(ref_sim_mat)) {
    if (nrow(ref_sim_mat) != n_rows) {
      stop("'sim_mat' and 'ref_sim_mat' must have the same number of temporal rows.")
    }
    base_dens <- rowMeans(ref_sim_mat)
  } else {
    base_dens <- rowMeans(sim_mat)
  }
  origin <- compute_doby_origin(base_dens, grid$doy)

  shifted_mat <- sim_mat[origin$shift_order, , drop = FALSE]
  idx_seq <- seq_len(n_rows)
  doby_draws <- as.numeric(crossprod(idx_seq, shifted_mat))

  mean_doby <- mean(doby_draws)
  low_doby <- stats::quantile(doby_draws, 0.025)
  high_doby <- stats::quantile(doby_draws, 0.975)

  return(list(
    Mean = wrap_doby_to_doy(mean_doby, origin$D_min, dt),
    Lower_CI = wrap_doby_to_doy(low_doby, origin$D_min, dt),
    Upper_CI = wrap_doby_to_doy(high_doby, origin$D_min, dt),
    Posterior_Draws = wrap_doby_to_doy(doby_draws, origin$D_min, dt),
    DOBY_Draws = doby_draws,
    D_min = origin$D_min
  ))
}
