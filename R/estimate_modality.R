#' Estimate Phenological Modality (Number of Activity Peaks)
#'
#' Counts the number of distinct activity peaks across simulated posterior
#' probability density curves using a two-step signal-processing filter after
#' rotating the temporal axis onto the Day of Biological Year (DOBY) origin
#' (`D_min`). Rotating to `D_min` ensures that winter activity modes straddling
#' December 31 and January 1 lie in the interior of the curve rather than on the
#' calendar boundary.
#'
#' @param sim_mat A numeric matrix (`n_grid x n_sims`, typically `365 x 1000`) of normalized posterior probability density curves generated by [simulate_posterior_density()].
#' @param rel_prominence Numeric, minimum relative trough drop between adjacent peaks (default = `0.50`).
#' @param abs_threshold Numeric, minimum peak height relative to the global maximum density (default = `0.25`).
#' @param ref_sim_mat Optional reference posterior density matrix (`n_grid x n_sims`) used to anchor `D_min` consistently across gradients. Defaults to `NULL`.
#' @return A list containing the posterior `Mean`, `Lower_CI` (2.5%), `Upper_CI` (97.5%), `Prob_Multimodal` (posterior probability of `>= 2` peaks), `Posterior_Draws`, and `D_min`.
#' @examples
#' data(sim_carabids)
#' mod <- mgcv::gam(
#'   Count ~ s(DOY, bs = "cc", k = 12) + offset(LogEffort),
#'   family = poisson(), data = sim_carabids,
#'   knots = list(DOY = c(0.5, 365.5))
#' )
#' nd <- create_newdata(mod, doy = "DOY")
#' sim <- simulate_posterior_density(mod, nd, n_sims = 100, warnings = FALSE)
#' estimate_modality(sim)$Mean
#' @export
estimate_modality <- function(sim_mat, rel_prominence = 0.50, abs_threshold = 0.25, ref_sim_mat = NULL) {
  grid <- get_doy_grid(sim_mat)
  base_dens <- if (!is.null(ref_sim_mat)) rowMeans(ref_sim_mat) else rowMeans(sim_mat)
  origin <- compute_doby_origin(base_dens, grid$doy)
  shifted_mat <- sim_mat[origin$shift_order, , drop = FALSE]

  count_peaks <- function(dens) {
    diffs <- diff(dens)
    signs <- sign(diffs)
    signs[signs == 0] <- -1
    peaks <- which(diff(signs) == -2) + 1

    # Step 1: Absolute height filter relative to global maximum
    global_max <- max(dens)
    peaks <- peaks[dens[peaks] >= (abs_threshold * global_max)]

    if (length(peaks) <= 1) return(max(1L, length(peaks)))

    # Step 2: Relative trough prominence filter
    valid_peaks <- peaks[1]
    for (i in 2:length(peaks)) {
      trough_val <- min(dens[valid_peaks[length(valid_peaks)]:peaks[i]])
      peak_min_height <- min(dens[valid_peaks[length(valid_peaks)]], dens[peaks[i]])
      if ((peak_min_height - trough_val) / peak_min_height >= rel_prominence) {
        valid_peaks <- c(valid_peaks, peaks[i])
      } else {
        if (dens[peaks[i]] > dens[valid_peaks[length(valid_peaks)]]) {
          valid_peaks[length(valid_peaks)] <- peaks[i]
        }
      }
    }
    return(length(valid_peaks))
  }

  res <- apply(shifted_mat, 2, count_peaks)
  return(list(
    Mean = mean(res),
    Lower_CI = stats::quantile(res, 0.025),
    Upper_CI = stats::quantile(res, 0.975),
    Prob_Multimodal = mean(res > 1),
    Posterior_Draws = res,
    D_min = origin$D_min
  ))
}
