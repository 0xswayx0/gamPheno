#' Estimate Phenological Offset Shift Volume
#'
#' Calculates the bidirectional late-season senescence shift volume between a
#' focal/shifted posterior density matrix and a reference posterior density matrix
#' on the continuous Day of Biological Year (`DOBY`) timeline. For intraspecific
#' comparisons (`doby_origin = "auto"`), the shared `DOBY` origin is identified as
#' the minimum of the joint mean density curve restricted to the shortest circular
#' arc connecting the two scenarios' tracked `doby_origin` values; for two
#' independently fitted species models, `doby_origin = "auto"` anchors to
#' `ref_sim_mat`. When two curves are completely disjoint above
#' `threshold_fraction`, the separating crossing is located between the draw-wise
#' `DOBY` centroids.
#'
#' @param sim_mat A numeric matrix (`n_grid x n_sims`, typically `365 x 1000`) of normalized posterior density curves for the focal or shifted scenario, generated by [simulate_posterior_density()].
#' @param ref_sim_mat A numeric matrix (`n_grid x n_sims`, typically `365 x 1000`) of normalized posterior density curves for the reference scenario, generated by [simulate_posterior_density()].
#' @param threshold_fraction Numeric, density threshold fraction to filter winter tail noise (default = `0.05`).
#' @param doby_origin Specification of the shared `DOBY` integration origin (default = `"auto"`): `"auto"` (searches within the shortest circular arc between the two steepest-descent `doby_origin` values for intraspecific comparisons, or anchors to `ref_sim_mat` across distinct species models), `"scenario"` (unconstrained global `D_min` of the pooled mean curve of `sim_mat` and `ref_sim_mat` without model reference), `"ref"` (anchors strictly to `ref_sim_mat`), an integer or numeric calendar `DOY` in `(0, 366)` for a custom cut-point, or a reference simulation matrix.
#' @return A list containing the posterior `Mean`, `Lower_CI` (2.5%), `Upper_CI` (97.5%), `Posterior_Draws`, and the shared biological minimum day `D_min`.
#' @examples
#' data(sim_carabids)
#' mod <- mgcv::gam(
#'   Count ~ s(DOY, bs = "cc", k = 10) + ti(DOY, Latitude, bs = c("cc", "cr"), k = c(8, 4)) +
#'     s(Latitude, k = 4) + offset(LogEffort),
#'   family = poisson(), data = sim_carabids,
#'   knots = list(DOY = c(0.5, 365.5))
#' )
#' sim_north <- simulate_posterior_density(
#'   mod, create_newdata(mod, Latitude = "95%"), n_sims = 100, warnings = FALSE
#' )
#' sim_ref <- simulate_posterior_density(
#'   mod, create_newdata(mod, Latitude = "mean"), n_sims = 100, warnings = FALSE
#' )
#' estimate_offset(sim_north, sim_ref)$Mean
#' @export
estimate_offset <- function(sim_mat, ref_sim_mat, threshold_fraction = 0.05, doby_origin = "auto") {
  grid_ref <- get_doy_grid(ref_sim_mat)
  grid_sim <- get_doy_grid(sim_mat)
  if (grid_sim$n_rows != grid_ref$n_rows) {
    stop("'sim_mat' and 'ref_sim_mat' must have the same number of temporal rows.")
  }

  n_rows <- grid_sim$n_rows
  origin <- resolve_doby_origin(doby_origin, sim_mat, ref_sim_mat = ref_sim_mat, two_curve = TRUE)
  shift_order <- origin$shift_order
  alpha <- origin$alpha

  n_draws <- min(ncol(sim_mat), ncol(ref_sim_mat))
  res <- numeric(n_draws)
  idx_seq <- seq_len(n_rows)

  for (i in seq_len(n_draws)) {
    td_shift <- sim_mat[shift_order, i]
    rd_shift <- ref_sim_mat[shift_order, i]
    d <- td_shift - rd_shift

    if (max(abs(d)) <= 1e-15) {
      res[i] <- 0
      next
    }

    # 1. Carry forward non-zero signs across exact ties to avoid artificial zero-plateau flips
    s <- sign(d)
    nz <- which(s != 0)
    s[seq_len(nz[1])] <- s[nz[1]]
    zero_idx <- which(s == 0)
    if (length(zero_idx) > 0L) {
      for (z in zero_idx) s[z] <- s[z - 1L]
    }
    crossings <- which(diff(s) != 0)

    # 2. Filter active-season crossings using piecewise-linear intersection height
    valid_crossings <- integer(0)
    if (length(crossings) > 0L) {
      d0 <- abs(d[crossings])
      d1 <- abs(d[crossings + 1L])
      w <- ifelse(d0 + d1 > 0, d0 / (d0 + d1), 0)
      y_cross <- (1 - w) * td_shift[crossings] + w * td_shift[crossings + 1L]
      thr_min <- min(threshold_fraction * max(td_shift), threshold_fraction * max(rd_shift))
      valid_crossings <- crossings[y_cross > thr_min]
    }

    # Positive value indicates prolonged late-season activity in sim_mat relative to ref_sim_mat
    cdiff <- (cumsum(rd_shift) - cumsum(td_shift)) - alpha * (rd_shift[1] - td_shift[1])

    # 3. Select last active crossing or inter-centroid fallback for disjoint curves
    if (length(valid_crossings) == 0L) {
      c_td <- sum(idx_seq * td_shift)
      c_rd <- sum(idx_seq * rd_shift)
      k_min <- max(1L, as.integer(floor(min(c_td, c_rd))))
      k_max <- min(n_rows - 1L, max(k_min, as.integer(ceiling(max(c_td, c_rd)))))
      win <- k_min:k_max
      last_cross <- win[which.max(abs(cdiff[win]))]
    } else {
      last_cross <- valid_crossings[length(valid_crossings)]
    }

    res[i] <- cdiff[last_cross]
  }

  return(list(
    Mean = mean(res),
    Lower_CI = stats::quantile(res, 0.025),
    Upper_CI = stats::quantile(res, 0.975),
    Posterior_Draws = res,
    D_min = origin$D_min
  ))
}
