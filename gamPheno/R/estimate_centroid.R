#' Estimate Phenological Centroid (Day of Biological Year)
#'
#' Calculates the circular, abundance-weighted centroid across simulated posterior
#' probability density curves using the Day of Biological Year (`DOBY`) axis
#' rotation and closed-form fractional boundary splitting. Posterior summaries
#' (`Mean`, `Lower_CI`, `Upper_CI`) are computed on the continuous unwrapped
#' timeline prior to modulo back-transformation onto calendar `DOY`, preventing
#' artificial boundary averaging across December 31 / January 1 and eliminating
#' discrete 1-day integer rotation steps along continuous environmental gradients.
#'
#' @param sim_mat A numeric matrix (`n_grid x n_sims`, typically `365 x 1000`) of normalized posterior probability density curves generated by [simulate_posterior_density()].
#' @param doby_origin Specification of the biological-year origin (`D_min`): `"auto"` (default; uses the dynamic path-tracked steepest-descent `doby_origin` attached by [simulate_posterior_density()]), `"scenario"` (computes the unconstrained global minimum directly from `sim_mat` without reference to the model baseline), an integer or numeric calendar `DOY` in `(0, 366)` for a custom cut-point, or a reference simulation matrix.
#' @return A list containing the posterior `Mean`, `Lower_CI` (2.5%), `Upper_CI` (97.5%) on the calendar `DOY` scale, `Posterior_Draws` (calendar `DOY`), `DOBY_Draws` (unwrapped biological-year coordinates), and the biological minimum day `D_min`.
#' @examples
#' data(sim_carabids)
#' mod <- mgcv::gam(
#'   Count ~ s(DOY, bs = "cc", k = 10) + s(Latitude, k = 4) + offset(LogEffort),
#'   family = poisson(), data = sim_carabids,
#'   knots = list(DOY = c(0.5, 365.5))
#' )
#' nd <- create_newdata(mod, doy = "DOY", Latitude = "mean")
#' sim <- simulate_posterior_density(mod, nd, n_sims = 100, warnings = FALSE)
#' estimate_centroid(sim)$Mean
#' @export
estimate_centroid <- function(sim_mat, doby_origin = "auto") {
  grid <- get_doy_grid(sim_mat)
  dt <- grid$dt
  origin <- resolve_doby_origin(doby_origin, sim_mat, two_curve = FALSE)

  c_linear <- as.numeric(crossprod(grid$doy, sim_mat))
  m <- origin$m
  alpha <- origin$alpha
  wrap_mass <- if (m > 1L) colSums(sim_mat[seq_len(m - 1L), , drop = FALSE]) else numeric(ncol(sim_mat))
  if (alpha > 0) {
    wrap_mass <- wrap_mass + alpha * as.numeric(sim_mat[m, ])
  }
  c_unwrapped <- c_linear + 365 * wrap_mass
  doby_draws <- (c_unwrapped - origin$D_min) / dt + 1

  mean_unw <- mean(c_unwrapped)
  low_unw <- stats::quantile(c_unwrapped, 0.025)
  high_unw <- stats::quantile(c_unwrapped, 0.975)

  return(list(
    Mean = wrap_unwrapped_doy(mean_unw),
    Lower_CI = wrap_unwrapped_doy(low_unw),
    Upper_CI = wrap_unwrapped_doy(high_unw),
    Posterior_Draws = wrap_unwrapped_doy(c_unwrapped),
    DOBY_Draws = doby_draws,
    D_min = origin$D_min
  ))
}
